import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
const appRoot = join(repositoryRoot, 'prototype-app');
const packageRoot = join(appRoot, 'policy-packages', 'agcf');
// V3 shipped the original repair. Keep it immutable because Flyway has already
// recorded its checksum in existing environments; V5 is the forward-only
// reconciliation migration for the finalized Phase 1 + 2 manifests.
const target = join(appRoot, 'backend/src/main/resources/db/migration/postgres_reset/V5__reconcile_bundled_ai_grid_catalog.sql');
const sql = (value) => value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => sql(JSON.stringify(value));
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

const manifests = await Promise.all(['phase-1-manifest.json', 'phase-2-manifest.json'].map(async (name) =>
  JSON.parse(await readFile(join(packageRoot, name), 'utf8')),
));
const packages = (await Promise.all(manifests.flatMap((manifest) => manifest.policies).map(async (item) => {
  const bytes = await readFile(join(packageRoot, item.policyId, `${item.version}.json`), 'utf8');
  const packageDigest = digest(bytes);
  if (packageDigest !== item.digest) throw new Error(`${item.policyId}@${item.version} does not match its manifest digest`);
  return { policy: JSON.parse(bytes), packageDigest };
}))).sort(({ policy: left }, { policy: right }) => left.policyId.localeCompare(right.policyId));

const objectives = new Map();
const facts = new Map();
for (const { policy } of packages) {
  objectives.set(policy.controlObjectiveId, policy);
  for (const fact of policy.requiredFacts ?? []) facts.set(fact.factKey, fact);
}
const objectiveRows = [...objectives.values()].map((policy) =>
  `(${sql(policy.controlObjectiveId)},${sql(policy.name)},${sql(policy.securityIntent)},${sql(policy.remediationIntent)},${sql(policy.owner)},'ACTIVE')`,
).join(',\n');
const factRows = [...facts.entries()].map(([factKey, fact]) =>
  `(${sql(factKey)},'1.0.0',${sql(fact.valueType)},${sql(`Canonical bundled catalog evidence for ${factKey}.`)},${json(fact.evidenceClasses)},${json(['POSTURE_FINDING', 'VALIDATED_EXPOSURE'])},${Number(fact.maxAgeSeconds)})`,
).join(',\n');
const policyRows = packages.map(({ policy, packageDigest }) => `(${[
  sql(policy.policyId), sql(policy.version), sql(policy.name), sql(policy.description), sql('HIGH'), sql('VALIDATED'),
  sql(policy.workflowClass), sql(policy.defaultSelection), json(policy.artifactTypes), json(policy.nativeKinds),
  json(policy.requiredCapabilities), json(policy.requiredRelationships), json(policy.requiredResourceFamilies),
  json(policy.requiredFacts), json(policy.evaluationDefinition?.artifactFacts?.predicate ?? {}),
  sql(policy.reasonCode ?? `AGCF_${policy.policyId.replaceAll('-', '_')}`), sql(policy.remediationIntent),
  json(policy.frameworkMappings), sql('STATIC'), json(policy.parameterDefinitions ?? []), sql(packageDigest),
  sql(policy.packageSourceRef), sql(policy.owner), sql(policy.controlObjectiveId), sql(policy.provider),
  sql(policy.evaluationMode), json(policy.evaluationDefinition), json(policy.baseEvidenceTiers ?? []),
  json(policy.conditionalCapabilities ?? []), json(policy.certificationParameterProfile ?? null),
  sql(policy.releaseFamily), sql(policy.wave),
].join(',')})`).join(',\n');
const expectedRows = packages.map(({ policy, packageDigest }) =>
  `(${sql(policy.policyId)},${sql(policy.version)},${sql(packageDigest)},${sql(policy.packageSourceRef)})`,
).join(',\n');
const distributionRows = packages.map(({ policy }) =>
  `(${sql(policy.policyId)},false,${sql(policy.defaultSelection)},'PAUSED','ai-grid-catalog-reconciliation')`,
).join(',\n');

const content = `-- migration-guard: platform-only
-- Generated by scripts/generate-ai-grid-catalog-repair.mjs. Do not edit by hand.
-- Reconciles databases that applied the original bundled-catalog repair before
-- the finalized Phase 1 + 2 package digests were available.

INSERT INTO platform.ai_grid_control_objectives
    (control_objective_id,name,security_intent,remediation_intent,owner,lifecycle)
VALUES
${objectiveRows}
ON CONFLICT (control_objective_id) DO NOTHING;

INSERT INTO platform.ai_grid_fact_definitions
    (fact_key,version,value_type,claim_semantics,allowed_evidence_classes_json,allowed_workflow_uses_json,default_max_age_seconds)
VALUES
${factRows}
ON CONFLICT (fact_key,version) DO NOTHING;

INSERT INTO platform.ai_grid_policy_versions
    (policy_id,version,name,description,severity,lifecycle,workflow_class,default_selection,artifact_types_json,native_kinds_json,
     required_capabilities_json,required_relationships_json,required_resource_families_json,required_facts_json,predicate_json,reason_code,
     remediation,framework_mappings_json,scope_resolution,parameter_definitions_json,package_digest,package_source_ref,authored_by,
     control_objective_id,provider,evaluation_mode,evaluation_definition_json,base_evidence_tiers_json,conditional_capabilities_json,
     certification_parameter_profile_json,release_family,release_wave)
VALUES
${policyRows}
ON CONFLICT (policy_id,version) DO NOTHING;

-- Record the exact approval before changing any legacy active package digest.
WITH expected (policy_id,version,package_digest,package_source_ref) AS (
    VALUES
${expectedRows}
), changed AS (
    SELECT expected.*
      FROM expected
      JOIN platform.ai_grid_policy_versions policy
        ON policy.policy_id = expected.policy_id AND policy.version = expected.version
     WHERE policy.package_digest IS DISTINCT FROM expected.package_digest
        OR policy.package_source_ref IS DISTINCT FROM expected.package_source_ref
)
INSERT INTO platform.ai_grid_policy_release_decisions
    (id,policy_id,policy_version,decision,reason,decided_by,package_digest,approved_package_digest)
SELECT md5('ai-grid-bundled-catalog-reconciliation:' || policy_id || ':' || version || ':' || package_digest)::uuid,
       policy_id,version,'APPROVED','Bundled catalog digest reconciliation','ai-grid-catalog-reconciliation',package_digest,package_digest
FROM changed
ON CONFLICT (id) DO NOTHING;

-- These triggers protect ordinary edits. This controlled repair updates the corresponding
-- approval and distribution binding in the same transaction.
ALTER TABLE platform.ai_grid_policy_versions DISABLE TRIGGER trg_ai_grid_approved_package_immutable;
ALTER TABLE platform.ai_grid_policy_versions DISABLE TRIGGER trg_ai_grid_phase_1_preview_digest_change;
ALTER TABLE platform.ai_grid_policy_distribution DISABLE TRIGGER trg_ai_grid_distribution_approval;

WITH expected (policy_id,version,package_digest,package_source_ref) AS (
    VALUES
${expectedRows}
)
UPDATE platform.ai_grid_policy_distribution distribution
   SET approved_package_digest = expected.package_digest,
       release_decision_id = md5('ai-grid-bundled-catalog-reconciliation:' || expected.policy_id || ':' || expected.version || ':' || expected.package_digest)::uuid,
       updated_by = 'ai-grid-catalog-reconciliation',
       updated_at = now()
  FROM expected
  JOIN platform.ai_grid_policy_versions policy
    ON policy.policy_id = expected.policy_id AND policy.version = expected.version
 WHERE distribution.policy_id = expected.policy_id
   AND distribution.pinned_version = expected.version
   AND (policy.package_digest IS DISTINCT FROM expected.package_digest
        OR policy.package_source_ref IS DISTINCT FROM expected.package_source_ref);

WITH expected (policy_id,version,package_digest,package_source_ref) AS (
    VALUES
${expectedRows}
), changed AS (
    SELECT expected.*
      FROM expected
      JOIN platform.ai_grid_policy_versions policy
        ON policy.policy_id = expected.policy_id AND policy.version = expected.version
     WHERE policy.package_digest IS DISTINCT FROM expected.package_digest
        OR policy.package_source_ref IS DISTINCT FROM expected.package_source_ref
)
UPDATE platform.ai_grid_policy_versions policy
   SET package_digest = expected.package_digest,
       package_source_ref = expected.package_source_ref
  FROM changed expected
 WHERE policy.policy_id = expected.policy_id
   AND policy.version = expected.version
   AND (policy.package_digest IS DISTINCT FROM expected.package_digest
        OR policy.package_source_ref IS DISTINCT FROM expected.package_source_ref);

ALTER TABLE platform.ai_grid_policy_versions ENABLE TRIGGER trg_ai_grid_phase_1_preview_digest_change;
ALTER TABLE platform.ai_grid_policy_versions ENABLE TRIGGER trg_ai_grid_approved_package_immutable;
ALTER TABLE platform.ai_grid_policy_distribution ENABLE TRIGGER trg_ai_grid_distribution_approval;

INSERT INTO platform.ai_grid_policy_distribution
    (policy_id,available,default_selection,rollout_stage,updated_by)
VALUES
${distributionRows}
ON CONFLICT (policy_id) DO NOTHING;
`;

await writeFile(target, content);
console.log(`Generated ${target} with ${packages.length} bundled policies and ${facts.size} facts.`);
