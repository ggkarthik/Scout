import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const packageRoot = join(root, 'policy-packages', 'agcf');
const manifest = JSON.parse(await readFile(join(packageRoot, 'phase-2-certification-wave-1-manifest.json'), 'utf8'));
const sql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const packages = await Promise.all(manifest.policies.map(async (entry) => ({
  ...entry,
  policy: JSON.parse(await readFile(join(packageRoot, entry.policyId, `${entry.version}.json`), 'utf8')),
})));

const values = packages.map(({ policy, version, digest, packageSourceRef }) =>
  `(${sql(policy.policyId)},${sql(version)},${sql(digest)},${sql(packageSourceRef)},cast(${sql(JSON.stringify(policy.frameworkMappings))} as jsonb))`).join(',\n');

const content = `-- migration-guard: platform-only
-- Generated by scripts/generate-ai-grid-phase2-certification-migration.mjs.
-- Creates immutable 1.0.1 mapping releases for the evidence-certification wave.
-- Policy distribution remains PAUSED; validation governance owns approval and rollout.

with certification (policy_id, version, package_digest, package_source_ref, framework_mappings_json) as (
  values
${values}
)
insert into platform.ai_grid_policy_versions
    (policy_id,version,name,description,severity,lifecycle,workflow_class,default_selection,artifact_types_json,native_kinds_json,
     required_capabilities_json,required_relationships_json,required_resource_families_json,required_facts_json,predicate_json,reason_code,
     remediation,framework_mappings_json,scope_resolution,parameter_definitions_json,package_digest,package_source_ref,authored_by,
     control_objective_id,provider,evaluation_mode,evaluation_definition_json,base_evidence_tiers_json,conditional_capabilities_json,
     certification_parameter_profile_json,release_family,release_wave)
select p.policy_id,c.version,p.name,p.description,p.severity,'VALIDATED',p.workflow_class,p.default_selection,
       p.artifact_types_json,p.native_kinds_json,p.required_capabilities_json,p.required_relationships_json,
       p.required_resource_families_json,p.required_facts_json,p.predicate_json,p.reason_code,p.remediation,
       c.framework_mappings_json,p.scope_resolution,p.parameter_definitions_json,c.package_digest,c.package_source_ref,
       p.authored_by,p.control_objective_id,p.provider,p.evaluation_mode,p.evaluation_definition_json,
       p.base_evidence_tiers_json,p.conditional_capabilities_json,p.certification_parameter_profile_json,
       p.release_family,p.release_wave
  from platform.ai_grid_policy_versions p
  join certification c on c.policy_id=p.policy_id
 where p.version='1.0.0'
on conflict (policy_id,version) do nothing;
`;

const target = join(root, 'backend', 'src', 'main', 'resources', 'db', 'migration', 'postgres_reset', 'V4__ai_grid_phase_2_evidence_certification_wave.sql');
await writeFile(target, content);
console.log(`Generated ${target} with ${packages.length} immutable mapping releases.`);
