import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const packageRoot = join(root, 'policy-packages', 'agcf');
const manifest = JSON.parse(await readFile(join(packageRoot, 'phase-2-manifest.json'), 'utf8'));
const sql = (value) => value === null || value === undefined ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => sql(JSON.stringify(value));
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const packages = await Promise.all(manifest.policies.map(async (item) => {
  const bytes = await readFile(join(packageRoot, item.policyId, '1.0.0.json'), 'utf8');
  return { item, policy: JSON.parse(bytes), digest: digest(bytes) };
}));
const facts = new Map();
for (const { policy } of packages) for (const fact of policy.requiredFacts ?? []) facts.set(fact.factKey, fact);
const capabilities = [
  ['AWS_EFFECTIVE_ACCESS','AWS','AWS_DISCOVERY','EFFECTIVE_ACCESS',false,'Collect bounded IAM simulation and Access Analyzer decisions for discovered AI principals.'],
  ['AWS_LINKED_DATA_STORES','AWS','AWS_DISCOVERY','LINKED_DATA_STORES',false,'Collect read-only metadata for directly referenced AI data stores and AgentCore endpoints.'],
  ['AWS_CONSUMPTION_TELEMETRY','AWS','AWS_DISCOVERY','CONSUMPTION_TELEMETRY',false,'Collect aggregated Bedrock quota, budget, alarm, invocation, and token metadata.'],
  ['AWS_MODEL_DATA_PROVENANCE','AWS','AWS_DISCOVERY','MODEL_DATA_PROVENANCE',false,'Collect bounded model, dataset, registry, SBOM, and vulnerability provenance metadata.'],
  ['AZURE_EFFECTIVE_ACCESS','AZURE','AZURE_DISCOVERY','EFFECTIVE_ACCESS',false,'Collect bounded Azure role, deny-assignment, and effective-access metadata for discovered AI principals.'],
  ['AZURE_LINKED_DATA_STORES','AZURE','AZURE_DISCOVERY','LINKED_DATA_STORES',false,'Collect read-only metadata for directly linked Storage, OneLake, and Search resources.'],
  ['AZURE_SEARCH_MCP_SECURITY','AZURE','AZURE_DISCOVERY','SEARCH_MCP_SECURITY',false,'Collect secret-safe Search, Bot, and Foundry MCP security classifications.'],
  ['AZURE_CONSUMPTION_TELEMETRY','AZURE','AZURE_DISCOVERY','CONSUMPTION_TELEMETRY',false,'Collect aggregated Azure Monitor quota, budget, alert, request, and token metadata.'],
  ['AZURE_MODEL_DATA_PROVENANCE','AZURE','AZURE_DISCOVERY','MODEL_DATA_PROVENANCE',false,'Collect bounded Azure ML, registry, MLflow, SBOM, and vulnerability provenance metadata.'],
];
const capabilityRows = capabilities.map(([id, provider, connector, family, optional, remediation]) =>
  `(${sql(id)},${sql(provider)},${sql(connector)},${sql(family)},${optional},'ACTIVE',${sql(remediation)})`).join(',\n');
const objectiveRows = packages.map(({ policy }) =>
  `(${sql(policy.controlObjectiveId)},${sql(policy.name)},${sql(policy.securityIntent)},${sql(policy.remediationIntent)},${sql(policy.owner)},'ACTIVE')`).join(',\n');
const factRows = [...facts.entries()].map(([key, fact]) =>
  `(${sql(key)},'1.0.0',${sql(fact.valueType)},${sql(`Canonical Phase 2 provider evidence for ${key}.`)},${json(fact.evidenceClasses)},${json(['POSTURE_FINDING'])},${Number(fact.maxAgeSeconds)})`).join(',\n');
const policyRows = packages.map(({ policy, digest }) => `(${[
  sql(policy.policyId), sql(policy.version), sql(policy.name), sql(policy.description), sql('HIGH'), sql('VALIDATED'), sql(policy.workflowClass), sql(policy.defaultSelection),
  json(policy.artifactTypes), json(policy.nativeKinds), json(policy.requiredCapabilities), json(policy.requiredRelationships), json(policy.requiredResourceFamilies), json(policy.requiredFacts),
  json(policy.evaluationMode === 'CORRELATION_PATH' ? {} : policy.evaluationDefinition.artifactFacts.predicate), sql(policy.reasonCode ?? `AGCF_${policy.policyId.replaceAll('-', '_')}`), sql(policy.remediationIntent), json(policy.frameworkMappings),
  sql('STATIC'), json(policy.parameterDefinitions ?? []), sql(digest), sql(policy.packageSourceRef), sql(policy.owner), sql(policy.controlObjectiveId), sql(policy.provider), sql(policy.evaluationMode), json(policy.evaluationDefinition), json(policy.baseEvidenceTiers), json(policy.conditionalCapabilities), json(policy.certificationParameterProfile ?? null), sql(policy.releaseFamily), sql(policy.wave)
].join(',')})`).join(',\n');
const distributionRows = packages.map(({ policy }) => `(${sql(policy.policyId)},false,${sql(policy.defaultSelection)},'PAUSED','ai-grid-phase-2')`).join(',\n');
const replacementRows = JSON.parse(await readFile(join(packageRoot, 'phase-2-catalog-contract.json'), 'utf8')).replacements
  .map(({ predecessorPolicyId, successorPolicyId }) => `(${sql(predecessorPolicyId)},${sql(successorPolicyId)})`).join(',\n');
const content = `-- migration-guard: platform-only
-- Generated by scripts/generate-ai-grid-phase2-migration.mjs.
-- Installation is intentionally VALIDATED/PAUSED and performs no lifecycle action.

INSERT INTO platform.ai_grid_capability_definitions
    (capability_id,provider,connector,resource_family,optional,lifecycle,remediation)
VALUES
${capabilityRows}
ON CONFLICT (capability_id) DO NOTHING;

INSERT INTO platform.ai_grid_control_objectives
    (control_objective_id,name,security_intent,remediation_intent,owner,lifecycle)
VALUES
${objectiveRows}
ON CONFLICT (control_objective_id) DO NOTHING;

INSERT INTO platform.ai_grid_fact_definitions
    (fact_key,version,value_type,claim_semantics,allowed_evidence_classes_json,allowed_workflow_uses_json,default_max_age_seconds)
VALUES
${factRows}
ON CONFLICT (fact_key,version) DO NOTHING;

INSERT INTO platform.ai_grid_policy_versions
    (policy_id,version,name,description,severity,lifecycle,workflow_class,default_selection,artifact_types_json,native_kinds_json,
     required_capabilities_json,required_relationships_json,required_resource_families_json,required_facts_json,predicate_json,reason_code,
     remediation,framework_mappings_json,scope_resolution,parameter_definitions_json,package_digest,package_source_ref,authored_by,
     control_objective_id,provider,evaluation_mode,evaluation_definition_json,base_evidence_tiers_json,conditional_capabilities_json,
     certification_parameter_profile_json,release_family,release_wave)
VALUES
${policyRows}
ON CONFLICT (policy_id,version) DO NOTHING;

INSERT INTO platform.ai_grid_policy_distribution
    (policy_id,available,default_selection,rollout_stage,updated_by)
VALUES
${distributionRows}
ON CONFLICT (policy_id) DO NOTHING;

CREATE TABLE IF NOT EXISTS platform.ai_grid_policy_replacements (
    predecessor_policy_id varchar(128) PRIMARY KEY,
    successor_policy_id varchar(128) NOT NULL UNIQUE,
    release_family varchar(64) NOT NULL DEFAULT 'AGCF_PHASE_2',
    created_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO platform.ai_grid_policy_replacements (predecessor_policy_id,successor_policy_id)
VALUES
${replacementRows}
ON CONFLICT (predecessor_policy_id) DO NOTHING;
`;
const target = join(root, 'backend', 'src', 'main', 'resources', 'db', 'migration', 'postgres_reset', 'V97__ai_grid_phase_2_catalog_installation.sql');
await writeFile(target, content);
console.log(`Generated ${target} with ${packages.length} packages and ${facts.size} facts.`);
